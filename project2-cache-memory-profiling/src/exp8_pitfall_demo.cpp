// Experiment 8: benchmark pitfalls, each demonstrated with data.
//   (a) cache reuse mistaken for DRAM: a "512 MiB streaming" benchmark whose
//       chunk index is masked into a 256 KiB window, while the bandwidth is
//       still computed as if 512 MiB had been streamed.
//   (b) thread pinning / isolation: dependent-chase latency per 25 ms window
//       with (1) pinned+high priority vs (2) unpinned+normal priority, on an
//       idle machine and with 24 busy-spinning background threads.
//   (c) first-touch: reading freshly committed (never-written) memory vs the
//       same memory after it has been touched once.
//
//   (d) address generation inside the timed loop: the same 1 GiB of random
//       independent line loads with precomputed addresses vs. addresses
//       generated by a PRNG in the loop (inline, or batched): the PRNG
//       version halves a core's memory-level parallelism.
//
// Usage: exp8_pitfall_demo.exe <cache_reuse_csv> <pinning_csv> <first_touch_csv> <addr_gen_csv>
#include "chase.hpp"
#include "kern.hpp"

using namespace bench;

int main(int argc, char** argv) {
    if (argc != 5) { std::cerr << "usage: " << argv[0] << " <cache_reuse_csv> <pinning_csv> <first_touch_csv> <addr_gen_csv>\n"; return 1; }
    const int bench_cpu = 4;
    init_timing_env(bench_cpu);
    volatile uint64_t sink = 0;

    // ------------------------------- (a) -----------------------------------
    {
        CsvWriter csv(argv[1], "variant,rep,claimed_gbps,unique_bytes_gbps");
        const size_t REGION = 512ull << 20, WINDOW = 256ull << 10, CH = 40960;
        char* buf = alloc_pages(REGION, true);
        const size_t chunks = REGION / CH;                 // "one pass over 512 MiB"
        for (int variant = 0; variant < 2; ++variant) for (int r = 0; r < 7; ++r) {
            auto t0 = Clock::now();
            for (int pass = 0; pass < 4; ++pass)
                for (size_t c = 0; c < chunks; ++c) {
                    size_t pos = variant == 0 ? (c * CH) % (WINDOW - CH + 1) / 512 * 512   // BUG: index masked into 256 KiB
                                              : c * CH;                                    // correct: spans all 512 MiB
                    sink += kern::read_seq(buf + pos, CH);
                }
            double dt = seconds_since(t0);
            double claimed = 4.0 * chunks * CH / dt / 1e9;
            double unique = (variant == 0 ? (double)WINDOW : (double)REGION) / (dt / 4) / 1e9;   // distinct bytes per pass / pass time
            csv.row(variant == 0 ? "buggy_masked_to_256KiB" : "fixed_full_512MiB", r, claimed, unique);
        }
        free_pages(buf);
    }

    // ------------------------------- (b) -----------------------------------
    {
        CsvWriter csv(argv[2], "condition,window,ns_per_hop,cpu");
        Chase c; c.build(layout_random_lines((256ull << 20) / 64, 2024));
        if (!c.verify()) { std::cerr << "VALIDATION FAILED chase\n"; return 2; }
        const int windows = 60; const long hops_per_window = 200000;
        std::atomic<bool> stop{false};
        std::vector<std::thread> busy;
        auto start_load = [&] {
            stop = false;
            for (int i = 0; i < 24; ++i) busy.emplace_back([&] { volatile uint64_t x = 0; while (!stop) x += 1; });
        };
        auto stop_load = [&] { stop = true; for (auto& t : busy) t.join(); busy.clear(); };
        struct Cond { const char* name; bool pinned; bool loaded; };
        for (Cond cd : { Cond{"pinned_idle", true, false}, Cond{"unpinned_idle", false, false},
                         Cond{"pinned_loaded", true, true}, Cond{"unpinned_loaded", false, true} }) {
            if (cd.loaded) start_load();
            if (cd.pinned) { SetPriorityClass(GetCurrentProcess(), HIGH_PRIORITY_CLASS); pin_thread(bench_cpu); SetThreadPriority(GetCurrentThread(), THREAD_PRIORITY_HIGHEST); }
            else { SetPriorityClass(GetCurrentProcess(), NORMAL_PRIORITY_CLASS); SetThreadAffinityMask(GetCurrentThread(), 0xFFFFFFFFull); SetThreadPriority(GetCurrentThread(), THREAD_PRIORITY_NORMAL); }
            Sleep(100);
            uint32_t off = c.start; off = chase_run(c.base, off, 500000);
            for (int w = 0; w < windows; ++w) {
                auto t0 = Clock::now();
                off = chase_run(c.base, off, hops_per_window);
                double ns = seconds_since(t0) * 1e9 / hops_per_window;
                csv.row(cd.name, w, ns, (int)GetCurrentProcessorNumber());
            }
            if (cd.loaded) stop_load();
        }
        SetPriorityClass(GetCurrentProcess(), HIGH_PRIORITY_CLASS); pin_thread(bench_cpu);
    }

    // ------------------------------- (c) -----------------------------------
    {
        CsvWriter csv(argv[3], "state,rep,gbps");
        const size_t B = 1ull << 30;
        for (int r = 0; r < 4; ++r) {
            char* p = alloc_pages(B, false);                  // committed but never written
            auto t0 = Clock::now(); sink += kern::read_seq(p, B); double cold = B / seconds_since(t0) / 1e9;
            t0 = Clock::now(); sink += kern::read_seq(p, B); double warm = B / seconds_since(t0) / 1e9;
            csv.row("first_pass_untouched", r, cold); csv.row("second_pass", r, warm);
            free_pages(p);
        }
    }

    // ------------------------------- (d) -----------------------------------
    {
        CsvWriter csv(argv[4], "variant,rep,ns_per_line,gbps");
        const size_t B = 1ull << 30; char* r = alloc_pages(B, true);
        const size_t n = B / 64; const uint64_t mask = n - 1;
        std::vector<uint32_t> perm(n), rep(n);
        for (size_t i = 0; i < n; ++i) perm[i] = (uint32_t)(i * 64);
        std::shuffle(perm.begin(), perm.end(), std::mt19937_64(1));
        { std::mt19937_64 g(2); for (size_t i = 0; i < n; ++i) rep[i] = (uint32_t)((g() & mask) << 6); }
        const int reps = 7;
        auto emit = [&](const char* name, const std::vector<double>& t) {
            for (int k = 0; k < reps; ++k) csv.row(name, k, t[k] * 1e9 / n, n * 64 / t[k] / 1e9);
        };
        emit("precomputed_permutation", timed_reps([&]{ sink += kern::read_lines_at(r, perm.data(), n); }, reps, 0.2));
        emit("precomputed_with_replacement", timed_reps([&]{ sink += kern::read_lines_at(r, rep.data(), n); }, reps, 0.2));
        emit("inline_xorshift_in_loop", timed_reps([&]{
            uint64_t s = 88172645463325252ull; __m512i a0 = _mm512_setzero_si512(), a1 = a0, a2 = a0, a3 = a0;
            for (size_t i = 0; i < n; i += 4) {
                a0 = _mm512_add_epi32(a0, _mm512_load_si512(r + ((kern::xorshift(s) & mask) << 6)));
                a1 = _mm512_add_epi32(a1, _mm512_load_si512(r + ((kern::xorshift(s) & mask) << 6)));
                a2 = _mm512_add_epi32(a2, _mm512_load_si512(r + ((kern::xorshift(s) & mask) << 6)));
                a3 = _mm512_add_epi32(a3, _mm512_load_si512(r + ((kern::xorshift(s) & mask) << 6)));
            }
            sink += kern::reduce(_mm512_add_epi32(_mm512_add_epi32(a0, a1), _mm512_add_epi32(a2, a3))); }, reps, 0.2));
        emit("xorshift_batched_64_then_load", timed_reps([&]{
            uint64_t s = 88172645463325252ull; uint64_t acc = 0; uint32_t buf[64];
            for (size_t i = 0; i < n; i += 64) { for (int k = 0; k < 64; ++k) buf[k] = (uint32_t)((kern::xorshift(s) & mask) << 6); acc += kern::read_lines_at(r, buf, 64); }
            sink += acc; }, reps, 0.2));
        free_pages(r);
    }
    std::cerr << "done: pitfalls (sink=" << sink << ")\n";
    return 0;
}
